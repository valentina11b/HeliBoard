package helium314.keyboard.latin

import android.content.Context
import android.media.AudioAttributes
import android.media.SoundPool
import android.os.Build
import android.os.VibrationEffect
import android.os.Vibrator
import helium314.keyboard.latin.common.Constants
import helium314.keyboard.keyboard.internal.keyboard_parser.floris.KeyCode
import kotlin.random.Random

/** Key sounds and vibrations for the Mechanical style, using one of the sound packs in res/raw. */
class MechanicalFeedback(context: Context, val pack: String) {
    private val soundPool = SoundPool.Builder()
        .setMaxStreams(4)
        .setAudioAttributes(AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_ASSISTANCE_SONIFICATION)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build())
        .build()
    private val ids = PACKS[pack] ?: PACKS.getValue(DEFAULT_PACK)
    private val keySounds = ids.take(3).map { soundPool.load(context, it, 1) }
    private val deleteSound = soundPool.load(context, ids[3], 1)
    private val enterSound = soundPool.load(context, ids[4], 1)
    private val spaceSound = soundPool.load(context, ids[5], 1)

    /** [volume] is the user's key sound volume, negative means system default. */
    fun playSound(code: Int, volume: Float) {
        val sound = when (code) {
            KeyCode.DELETE -> deleteSound
            Constants.CODE_ENTER -> enterSound
            Constants.CODE_SPACE -> spaceSound
            else -> keySounds.random()
        }
        val v = if (volume < 0) DEFAULT_VOLUME else volume
        // slight pitch variation so repeated keys don't sound identical
        soundPool.play(sound, v, v, 1, 0, Random.nextDouble(0.95, 1.05).toFloat())
    }

    /** Vibrates with the [vibrationPack] pattern, returns false if the device can't, so the caller can fall back. */
    fun vibrate(vibrator: Vibrator, code: Int, vibrationPack: String): Boolean {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) return false
        val big = code == KeyCode.DELETE || code == Constants.CODE_ENTER || code == Constants.CODE_SPACE
        val effect = composedEffect(vibrator, vibrationPack, big) ?: VibrationEffect.createPredefined(when (vibrationPack) {
            "soft" -> VibrationEffect.EFFECT_TICK
            "clicky" -> if (big) VibrationEffect.EFFECT_HEAVY_CLICK else VibrationEffect.EFFECT_DOUBLE_CLICK
            "thock", "typewriter" -> VibrationEffect.EFFECT_HEAVY_CLICK
            else -> if (big) VibrationEffect.EFFECT_HEAVY_CLICK else VibrationEffect.EFFECT_CLICK
        })
        vibrator.vibrate(effect)
        return true
    }

    /** Finer patterns built from haptic primitives, null if the device doesn't support them. */
    private fun composedEffect(vibrator: Vibrator, vibrationPack: String, big: Boolean): VibrationEffect? {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return null
        val primitives: List<Pair<Int, Float>> = when (vibrationPack) {
            // deep, dull bottom-out
            "thock" -> listOf(VibrationEffect.Composition.PRIMITIVE_THUD to if (big) 0.9f else 0.55f)
            // sharp click of the switch, then the click jacket snapping back
            "clicky" -> listOf(VibrationEffect.Composition.PRIMITIVE_CLICK to 1f, VibrationEffect.Composition.PRIMITIVE_TICK to 0.7f)
            // hard strike of the typebar
            "typewriter" -> listOf(VibrationEffect.Composition.PRIMITIVE_CLICK to 1f, VibrationEffect.Composition.PRIMITIVE_LOW_TICK to if (big) 1f else 0.6f)
            "soft" -> listOf(VibrationEffect.Composition.PRIMITIVE_LOW_TICK to if (big) 0.6f else 0.35f)
            else -> listOf(VibrationEffect.Composition.PRIMITIVE_CLICK to if (big) 1f else 0.7f)
        }
        if (!vibrator.areAllPrimitivesSupported(*primitives.map { it.first }.toIntArray())) return null
        val composition = VibrationEffect.startComposition()
        primitives.forEachIndexed { i, (primitive, scale) -> composition.addPrimitive(primitive, scale, if (i == 0) 0 else 25) }
        return composition.compose()
    }

    fun release() = soundPool.release()

    companion object {
        private const val DEFAULT_VOLUME = 0.6f
        const val DEFAULT_PACK = "classic"
        val PACK_NAMES = listOf("classic", "thock", "clicky", "typewriter", "soft")
        // per pack: three letter variants, delete, enter, space (generated by tools/generate_mechanical_sounds.py)
        val PACKS = mapOf(
            "classic" to listOf(R.raw.mech_classic_key_1, R.raw.mech_classic_key_2, R.raw.mech_classic_key_3,
                R.raw.mech_classic_delete, R.raw.mech_classic_enter, R.raw.mech_classic_space),
            "thock" to listOf(R.raw.mech_thock_key_1, R.raw.mech_thock_key_2, R.raw.mech_thock_key_3,
                R.raw.mech_thock_delete, R.raw.mech_thock_enter, R.raw.mech_thock_space),
            "clicky" to listOf(R.raw.mech_clicky_key_1, R.raw.mech_clicky_key_2, R.raw.mech_clicky_key_3,
                R.raw.mech_clicky_delete, R.raw.mech_clicky_enter, R.raw.mech_clicky_space),
            "typewriter" to listOf(R.raw.mech_typewriter_key_1, R.raw.mech_typewriter_key_2, R.raw.mech_typewriter_key_3,
                R.raw.mech_typewriter_delete, R.raw.mech_typewriter_enter, R.raw.mech_typewriter_space),
            "soft" to listOf(R.raw.mech_soft_key_1, R.raw.mech_soft_key_2, R.raw.mech_soft_key_3,
                R.raw.mech_soft_delete, R.raw.mech_soft_enter, R.raw.mech_soft_space),
        )
    }
}
